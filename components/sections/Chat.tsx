"use client";
import { useEffect, useRef, useState } from "react";
import { Send } from "lucide-react";
import { SwanMark } from "@/components/ui";

type Msg = { role: "user" | "assistant"; content: string };

const PROMPTS = [
  "Tell me about Hireish.",
  "What systems have you built?",
  "How do you reduce AI costs?",
  "What is SBANetwork?",
  "What is your backend experience?",
];

export function AbhishekAIChat({ mode }: { mode: "live" | "demo" }) {
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const log = useRef<HTMLDivElement>(null);

  useEffect(() => {
    // Scroll the chat log only, never the page.
    log.current?.scrollTo({ top: log.current.scrollHeight });
  }, [msgs, loading, error]);

  async function send(text: string) {
    const content = text.trim();
    if (!content || loading) return;
    const next = [...msgs, { role: "user" as const, content }];
    setMsgs(next);
    setInput("");
    setError("");
    setLoading(true);
    try {
      const res = await fetch("/api/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ messages: next.slice(-12) }),
      });
      const data = await res.json().catch(() => ({}));
      if (!res.ok || typeof data.reply !== "string") throw new Error(data.error || "Something went wrong.");
      setMsgs([...next, { role: "assistant", content: data.reply }]);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Something went wrong.");
    } finally {
      setLoading(false);
    }
  }

  const lastUser = [...msgs].reverse().find((m) => m.role === "user");

  return (
    <section id="chat" aria-labelledby="chat-title" className="border-b border-line">
      <div className="mx-auto grid max-w-[1600px] gap-10 px-5 py-16 sm:px-8 lg:grid-cols-12 lg:px-10 lg:py-24">
        <div className="lg:col-span-5">
          <h2 id="chat-title" className="text-3xl font-medium tracking-tight sm:text-4xl">
            Ask anything about my work, projects or tech stack.
          </h2>
          <p className="mt-4 max-w-md text-sm leading-relaxed text-muted">
            Answers come only from the information on this site.
            {mode === "demo" && " This instance is in demo mode, so answers are curated rather than generated by a language model."}
          </p>
        </div>

        <div className="lg:col-span-7">
          <div className="flex h-[34rem] flex-col border border-white/10 bg-dark text-[#f5f3ed] shadow-2xl">
            <header className="flex flex-wrap items-center justify-between gap-x-4 gap-y-2 border-b border-white/10 px-4 py-3">
              <div className="flex items-center gap-3">
                <span className="flex h-8 w-8 items-center justify-center bg-[#f5f3ed] p-1 text-ink">
                  <SwanMark className="h-full w-full" />
                </span>
                <span className="whitespace-nowrap text-sm font-medium">Personal Agent</span>
                <span className="label border border-white/20 px-1.5 py-0.5 text-[0.6rem] text-white/60">Beta</span>
              </div>
              <div className="label flex items-center gap-2 text-white/60">
                <span className={`h-1.5 w-1.5 ${mode === "live" ? "bg-accent" : "bg-white/40"}`} aria-hidden />
                {mode === "live" ? "Live" : "Demo mode"}
              </div>
            </header>

            <div ref={log} role="log" aria-live="polite" aria-label="Conversation" className="flex-1 space-y-3 overflow-y-auto p-4">
              <Bubble role="assistant">
                Hi, I&apos;m Abhishek&apos;s personal agent. Ask me about his projects, experience, tech stack or anything related to his work.
              </Bubble>
              {msgs.map((m, i) => (
                <Bubble key={i} role={m.role}>
                  {m.content}
                </Bubble>
              ))}
              {loading && (
                <Bubble role="assistant">
                  <span className="label text-white/60" aria-label="Thinking">
                    Thinking<span className="blink">_</span>
                  </span>
                </Bubble>
              )}
              {error && (
                <div role="alert" className="border border-accent/50 bg-accent/10 p-3 text-sm">
                  {error}
                  {lastUser && (
                    <button onClick={() => send(lastUser.content)} className="label ml-3 underline hover:text-accent">
                      Retry
                    </button>
                  )}
                </div>
              )}
            </div>

            <div className="border-t border-white/10 p-4">
              {msgs.length === 0 && (
                <div className="mb-3 flex flex-wrap gap-2">
                  {PROMPTS.map((p) => (
                    <button key={p} onClick={() => send(p)} disabled={loading} className="border border-white/20 px-3 py-1.5 text-xs text-white/80 hover:border-accent hover:text-white disabled:opacity-50">
                      {p}
                    </button>
                  ))}
                </div>
              )}
              <form
                onSubmit={(e) => {
                  e.preventDefault();
                  send(input);
                }}
                className="flex gap-2"
              >
                <label htmlFor="chat-input" className="sr-only">
                  Ask something
                </label>
                <input
                  id="chat-input"
                  value={input}
                  onChange={(e) => setInput(e.target.value)}
                  maxLength={1000}
                  placeholder="Ask something…"
                  autoComplete="off"
                  className="min-w-0 flex-1 border border-white/15 bg-transparent px-3 py-3 text-base placeholder:text-white/40 focus:border-accent focus:outline-none sm:text-sm"
                />
                <button
                  type="submit"
                  disabled={loading || !input.trim()}
                  aria-label="Send message"
                  className="flex h-12 w-12 shrink-0 items-center justify-center bg-accent text-white transition-opacity hover:opacity-90 disabled:opacity-40"
                >
                  <Send className="h-4 w-4" aria-hidden />
                </button>
              </form>
            </div>
          </div>
        </div>
      </div>
    </section>
  );
}

function Bubble({ role, children }: { role: "user" | "assistant"; children: React.ReactNode }) {
  const user = role === "user";
  return (
    <div className={`flex ${user ? "justify-end" : "justify-start"}`}>
      <div className={`max-w-[85%] whitespace-pre-wrap px-3.5 py-2.5 text-sm leading-relaxed ${user ? "bg-accent text-white" : "bg-white/[0.07] text-white/90"}`}>
        {children}
      </div>
    </div>
  );
}
